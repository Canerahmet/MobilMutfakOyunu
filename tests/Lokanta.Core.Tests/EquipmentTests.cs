    /// <summary>
    /// Station slots and equipment. docs/27-time-model.md Decision D:
    ///   - prepMs is the dish's WALL CLOCK time
    ///   - the cook is tied up for prepMs x attendBp / 10000
    ///   - an upgrade either adds a slot or lowers attendBp; it never touches
    ///     prepMs
    ///
    /// This file verifies that the decision is implemented and that the equipment
    /// makes a MEASURABLE difference. The equipment prices come from
    /// content/equipment.json and that file is generated by tools/balance.
    /// </summary>
    public class EquipmentTests
    {
        private readonly ITestOutputHelper _out;
        public EquipmentTests(ITestOutputHelper output) { _out = output; }

        private const ulong Seed = 20260910UL;

        private static EconomyConfig Economy() => ContentLoader.LoadEconomy(Paths.Content);
        private static ContentSet Content() => ContentSetLoader.Load(Paths.Content, "fastfood");

        private static TimingConfig Timing()
        {
            ContentSet c = Content();
            return c.SlotDurationsBp != null
                ? TimingConfig.Default().WithSlotDurations(c.SlotDurationsBp).WithEatMs(c.EatMs)
                : TimingConfig.Default();
        }

        private static Simulation NewSim()
        {
            return new Simulation(Economy(), Content(), Timing(), Seed);
        }

        /// <summary>
        /// The first station this cuisine actually uses.
        ///
        /// NOT STATION 0. These tests used to buy index 0 on the assumption
        /// that it is the hob and the hob is always in use. It stopped being
        /// true the day fast food's fried dishes moved to a fryer of their own
        /// (18 September): every one of its hob dishes was deep fried, so the
        /// cuisine no longer uses the hob at all - and the simulation is right
        /// to refuse to sell equipment for a station nothing cooks on.
        ///
        /// A test that names a station by INDEX is a test that will break the
        /// next time the closed list grows in the middle. This asks the
        /// simulation.
        /// </summary>
        private static int UsedStation(Simulation sim) { return UsedStation(sim, 0); }

        /// <summary>The nth station this cuisine uses.</summary>
        private static int UsedStation(Simulation sim, int nth)
        {
            int seen = 0;
            for (int i = 0; i < sim.StationCount; i++)
            {
                if (!sim.IsStationUsed(i)) continue;
                if (seen == nth) return i;
                seen++;
            }
            throw new Xunit.Sdk.XunitException(
                "the cuisine uses fewer than " + (nth + 1) + " stations");
        }

        /// <summary>
        /// Buys stock at the market in the morning. Without this the kitchen is
        /// empty: in the warm-up run the reputation fell to zero and the
        /// measurement became meaningless.
        /// </summary>
        private static void Restock(Simulation sim)
        {
            for (int i = 0; i < sim.IngredientCount; i++)
            {
                int need = sim.RecommendedRestock(i);
                if (need > 0)
                    sim.Apply(new Command(sim.TickIndex, CommandKind.OrderIngredient, i, need));
            }
        }

        /// <summary>
        /// Narrows the menu to three main courses. A wide menu both splits the
        /// stock and lowers satisfaction; this is why in the warm-up run the
        /// reputation stuck at 27 and only 26 parties came to fourteen tables.
        /// </summary>
        private static void NarrowMenu(Simulation sim)
        {
            int mains = 0;
            for (int i = 0; i < sim.DishCount; i++)
            {
                if (!sim.IsUnlocked(i)) continue;
                bool on = !sim.IsMain(i) || mains++ < 3;
                sim.Apply(new Command(sim.TickIndex, CommandKind.SetMenuSlot, i, on ? 1 : 0));
            }
        }

        private static DayReport RunOneDay(Simulation sim)
        {
            Restock(sim);
            sim.Apply(new Command(sim.TickIndex, CommandKind.OpenService));
            int limit = Timing().ServiceTicks + 4000;
            for (int t = 0; t < limit; t++)
            {
                sim.Tick();
                if (sim.ServiceComplete) break;
            }
            sim.Apply(new Command(sim.TickIndex, CommandKind.CloseDay));
            return sim.BuildDayReport();
        }

