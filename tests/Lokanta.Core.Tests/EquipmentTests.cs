        // Cold storage. docs/12 3: perishable stock loses all of its value when
        // the day closes. Cold storage is the upgrade that changes THAT GROUND
        // RULE; it brings the content's spoilDays field to life.
        // ================================================================
        [Fact]
        public void The_cold_storage_ladder_loads()
        {
            ContentSet c = Content();
            Assert.NotNull(c.Storage);
            Assert.True(c.Storage.Tiers.Length >= 2);
            Assert.Equal(0, c.Storage.Tiers[0].KeepBp);     // t0: it dies overnight
            Assert.Equal(0, c.Storage.Tiers[0].Price);
            for (int t = 1; t < c.Storage.Tiers.Length; t++)
            {
                Assert.True(c.Storage.Tiers[t].KeepBp > c.Storage.Tiers[t - 1].KeepBp);
                Assert.True(c.Storage.Tiers[t].Price > c.Storage.Tiers[t - 1].Price);
            }
            Assert.Equal(10000, c.Storage.Tiers[c.Storage.MaxTier].KeepBp);
        }

        [Fact]
        public void Without_cold_storage_perishable_stock_dies_overnight()
        {
            Simulation sim = NewSim();
            ContentSet c = Content();
            Restock(sim);

            int perishable = -1, keeps = -1;
            for (int i = 0; i < c.Ingredients.Length; i++)
            {
                if (c.Ingredients[i].Perishable && perishable < 0) perishable = i;
                if (!c.Ingredients[i].Perishable && keeps < 0) keeps = i;
            }
            Assert.True(perishable >= 0 && keeps >= 0);
            Assert.True(sim.StockOf(perishable) > 0);
            Assert.True(sim.StockOf(keeps) > 0);

            sim.Apply(new Command(sim.TickIndex, CommandKind.OpenService));
            sim.Apply(new Command(sim.TickIndex, CommandKind.CloseDay));

            Assert.Equal(0, sim.StockOf(perishable));
            Assert.True(sim.StockOf(keeps) > 0, "the non-perishable stock was deleted too");
        }

        [Fact]
        public void Cold_storage_buys_shelf_life()
        {
            // At the top tier an ingredient must live for ITS OWN spoilDays.
            // Onions 20 days, mince 1 day: the two must not die the same night.
            ContentSet c = Content();
            int longLife = -1, shortLife = -1;
            for (int i = 0; i < c.Ingredients.Length; i++)
            {
                if (!c.Ingredients[i].Perishable) continue;
                if (c.Ingredients[i].SpoilDays >= 10 && longLife < 0) longLife = i;
                if (c.Ingredients[i].SpoilDays == 1 && shortLife < 0) shortLife = i;
            }
            Assert.True(longLife >= 0, "there is no perishable ingredient that lives longer than ten days");
            Assert.True(shortLife >= 0, "there is no one-day perishable ingredient");

            Simulation sim = NewSim();
            sim.Apply(new Command(0, CommandKind.TakeLoan, 2));
            for (int k = 0; k < c.Storage.MaxTier; k++)
                sim.Apply(new Command(0, CommandKind.BuyStorage));
            Assert.Equal(c.Storage.MaxTier, sim.StorageTier);

            Restock(sim);
            int had = sim.StockOf(longLife);
            Assert.True(had > 0);

            // Close a day with no service: let only the spoilage run.
            sim.Apply(new Command(sim.TickIndex, CommandKind.OpenService));
            sim.Apply(new Command(sim.TickIndex, CommandKind.CloseDay));

            _out.WriteLine($"{c.Ingredients[longLife].Id} ({c.Ingredients[longLife].SpoilDays} days): " +
                           $"{had} -> {sim.StockOf(longLife)}");
            _out.WriteLine($"{c.Ingredients[shortLife].Id} ({c.Ingredients[shortLife].SpoilDays} days): " +
                           $"{sim.StockOf(shortLife)}");

            Assert.True(sim.StockOf(longLife) > 0, "the long-lived ingredient died even in cold storage");
            Assert.Equal(0, sim.StockOf(shortLife));
        }

        [Fact]
        public void Buying_one_gram_to_stop_the_clock_does_not_work()
        {
            // The age is a WEIGHTED AVERAGE. A simple "reset on purchase" rule
            // opened this exploit up: by buying one gram a day you could keep an
            // ingredient fresh for ever.
            ContentSet c = Content();
            int ing = -1;
            for (int i = 0; i < c.Ingredients.Length; i++)
                if (c.Ingredients[i].Perishable && c.Ingredients[i].SpoilDays >= 3
                    && c.Ingredients[i].SpoilDays <= 6) { ing = i; break; }
            Assert.True(ing >= 0);

            Simulation sim = NewSim();
            sim.Apply(new Command(0, CommandKind.TakeLoan, 2));
            for (int k = 0; k < c.Storage.MaxTier; k++)
                sim.Apply(new Command(0, CommandKind.BuyStorage));

            sim.Apply(new Command(sim.TickIndex, CommandKind.OrderIngredient, ing, 40_000));

            int survived = 0;
            for (int d = 0; d < 12; d++)
            {
                sim.Apply(new Command(sim.TickIndex, CommandKind.OrderIngredient, ing, 1));
                sim.Apply(new Command(sim.TickIndex, CommandKind.OpenService));
                sim.Apply(new Command(sim.TickIndex, CommandKind.CloseDay));
                // The threshold IS NOT ZERO. The daily one-gram purchase keeps
                // the stock technically above zero and it looks "alive"; what has
                // to be measured is whether THE FIRST BATCH survives.
                if (sim.StockOf(ing) > 1_000) survived++;
                sim.AdvanceToNextDay();
            }

            _out.WriteLine($"{c.Ingredients[ing].Id} ({c.Ingredients[ing].SpoilDays} days of shelf life): " +
                           $"survived {survived} days by buying one gram a day");
            Assert.True(survived <= c.Ingredients[ing].SpoilDays,
                $"the shelf life was beaten by buying one gram: {survived} > {c.Ingredients[ing].SpoilDays}");
        }

        [Fact]
        public void The_save_carries_the_equipment_tier_and_the_work_in_progress()
        {
            Simulation sim = NewSim();
            int a = UsedStation(sim, 0), b = UsedStation(sim, 1);
            sim.Apply(new Command(sim.TickIndex, CommandKind.BuyEquipment, a));
            sim.Apply(new Command(sim.TickIndex, CommandKind.BuyEquipment, b));

            // Save in the middle of service: there is work cooking at a station.
            sim.Apply(new Command(sim.TickIndex, CommandKind.OpenService));
            for (int t = 0; t < 1200; t++) sim.Tick();

            JsonStateWriter w = new JsonStateWriter();
            sim.Write(w);
            Simulation restored = NewSim();
            restored.Restore(new JsonStateReader(w.ToJson()));

            // The tiers must be NON-ZERO, or this compares nothing: the buys
            // above are refused for a station the cuisine does not use, and
            // 0 == 0 passes without testing the save at all.
            Assert.True(sim.StationTier(a) > 0, "the first buy did not take");
            Assert.Equal(sim.StationTier(a), restored.StationTier(a));
            Assert.Equal(sim.StationTier(b), restored.StationTier(b));
            Assert.Equal(sim.StateHash(), restored.StateHash());

            // It must end the same as an uninterrupted run: the slot counter is
            // DERIVED, so it is rebuilt; if it is rebuilt wrongly the kitchen
            // silently narrows and the difference is only visible here.
            for (int t = 0; t < 3600; t++) { sim.Tick(); restored.Tick(); }
            Assert.Equal(sim.StateHash(), restored.StateHash());
        }
